#!/usr/bin/env python3
"""Bundle the manifest runner into its ci-operator commands script."""

import argparse
from pathlib import Path


HERE = Path(__file__).resolve().parent
COMMANDS = HERE.parents[1] / (
    "ci-operator/step-registry/openshift/claude/agent-eval/manifest/"
    "openshift-claude-agent-eval-manifest-commands.sh")
SOURCES = ("eval_plan.py", "manifest_runner.py", "eval_metrics.py", "eval_report.py", "eval_regression.py",
           "eval-report.html", "eval-report.css")


def generated_script():
    # ci-operator ships this commands file, not the source files in release/hack.
    # The shell only unpacks the bundle and forwards signals; Python owns execution.
    script = '''#!/bin/bash
# Generated by hack/claude-agent-eval/sync_commands.py; do not edit.
set -euo pipefail

runner_dir="$(mktemp -d)"
trap 'rm -rf "${runner_dir}"' EXIT
'''
    for index, filename in enumerate(SOURCES):
        delimiter = f"PYTHON_SOURCE_{index}"
        source = (HERE / filename).read_text(encoding="utf-8")
        if delimiter in source.splitlines():
            raise ValueError(f"heredoc delimiter occurs in {filename}")
        script += f'cat > "${{runner_dir}}/{filename}" <<\'{delimiter}\'\n{source}{delimiter}\n'
    return script + '''
# Forward termination so Python can stop its children and preserve artifacts
# before the temporary source files are removed.
stop_runner() {
    kill -TERM "${runner_pid}" 2>/dev/null || true
    wait "${runner_pid}" || true
    exit "$1"
}
python3 "${runner_dir}/manifest_runner.py" &
runner_pid=$!
trap 'stop_runner 143' TERM
trap 'stop_runner 130' INT
status=0
wait "${runner_pid}" || status=$?
exit "${status}"
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    updated = generated_script()
    if args.check:
        if not COMMANDS.is_file() or COMMANDS.read_text(encoding="utf-8") != updated:
            parser.exit(1, f"Bundled Python is stale in {COMMANDS}; run python3 hack/claude-agent-eval/sync_commands.py\n")
    else:
        COMMANDS.write_text(updated, encoding="utf-8")


if __name__ == "__main__":
    main()
